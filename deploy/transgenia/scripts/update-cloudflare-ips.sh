#!/bin/sh
# Regenerate the Cloudflare edge ranges used by the meet.transgenia.org vhost:
#   /etc/nginx/snippets/meet-cloudflare-realip.conf  (server context)
#   /etc/nginx/conf.d/meet-transgenia.conf            (http context)
# Validates every line as a CIDR, tests the full nginx config and only then
# reloads (reload, not restart). Leaves the old files in place on any error.
set -eu
umask 022

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT

curl -fsS --max-time 15 https://www.cloudflare.com/ips-v4 -o "$tmpdir/v4"
curl -fsS --max-time 15 https://www.cloudflare.com/ips-v6 -o "$tmpdir/v6"
# The published files may lack a trailing newline; join them line-safely.
{ cat "$tmpdir/v4"; echo; cat "$tmpdir/v6"; echo; } | sed '/^\s*$/d' >"$tmpdir/all"
if [ "$(wc -l <"$tmpdir/all")" -lt 10 ] ||
	grep -vqE '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$|^[0-9a-f:]+/[0-9]{1,3}$' "$tmpdir/all"; then
	echo "unexpected Cloudflare IP list; nothing changed" >&2
	exit 1
fi

{
	echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
	sed 's/.*/set_real_ip_from &;/' "$tmpdir/all"
	echo "real_ip_header CF-Connecting-IP;"
	echo "real_ip_recursive off;"
} >"$tmpdir/realip.conf"

{
	echo "# Generated by update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
	echo "# Used only by sites-available/meet.transgenia.org.conf."
	echo 'geo $realip_remote_addr $meet_via_cloudflare {'
	echo "    default 0;"
	echo "    127.0.0.1 1;"
	sed 's/.*/    & 1;/' "$tmpdir/all"
	echo "}"
	echo 'limit_req_zone $binary_remote_addr zone=meet_login:10m rate=10r/m;'
	echo 'limit_req_zone $binary_remote_addr zone=meet_join:10m rate=30r/m;'
	echo 'limit_req_zone $binary_remote_addr zone=meet_general:10m rate=20r/s;'
	echo 'log_format meet_noquery '"'"'$remote_addr - [$time_local] "$request_method $uri $server_protocol" $status $body_bytes_sent $request_time "$http_user_agent"'"'"';'
} >"$tmpdir/http.conf"

snip=/etc/nginx/snippets/meet-cloudflare-realip.conf
http=/etc/nginx/conf.d/meet-transgenia.conf
for f in "$snip" "$http"; do [ -f "$f" ] && cp -p "$f" "$f.prev"; done
install -m 0644 "$tmpdir/realip.conf" "$snip"
install -m 0644 "$tmpdir/http.conf" "$http"

if ! nginx -t 2>"$tmpdir/nginx-t"; then
	cat "$tmpdir/nginx-t" >&2
	for f in "$snip" "$http"; do
		if [ -f "$f.prev" ]; then mv -f "$f.prev" "$f"; else rm -f "$f"; fi
	done
	echo "nginx -t failed; previous files restored, nginx not reloaded" >&2
	exit 1
fi
rm -f "$snip.prev" "$http.prev"
systemctl reload nginx
echo "Cloudflare ranges updated ($(wc -l <"$tmpdir/all") prefixes); nginx reloaded"
